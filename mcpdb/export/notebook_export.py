"""Jupyter notebook export — generates .ipynb from conversation + artifacts."""

from __future__ import annotations

import json
import logging
from typing import Any

from mcpdb.export.html_export import ExportArtifact, ExportMessage, ExportPayload

logger = logging.getLogger("mcpdb.export.notebook")


def render_notebook(payload: ExportPayload) -> dict[str, Any]:
    """Render a Jupyter notebook dict from the export payload."""
    cells: list[dict[str, Any]] = []

    # Title cell
    cells.append(_markdown_cell(f"# {payload.title}\n\n*Generated by MCPDB*"))

    # Metadata cell
    if payload.metadata:
        meta_lines = [f"- **{k}**: {v}" for k, v in payload.metadata.items()]
        cells.append(_markdown_cell("\n".join(meta_lines)))

    # Messages and artifacts interleaved
    artifact_by_step: dict[int, list[ExportArtifact]] = {}
    for art in payload.artifacts:
        artifact_by_step.setdefault(art.step_number, []).append(art)

    for i, msg in enumerate(payload.messages):
        if msg.role == "user":
            cells.append(_markdown_cell(f"**User:** {msg.content}"))
        else:
            cells.append(_markdown_cell(f"**Assistant:**\n\n{msg.content}"))

        # Insert artifacts associated with this step
        for art in artifact_by_step.get(i, []):
            if art.artifact_type == "code" and isinstance(art.data, str):
                cells.append(_code_cell(art.data, art.title))
            elif art.artifact_type == "table" and isinstance(art.data, dict):
                code = _table_to_pandas_code(art.data, art.title)
                cells.append(_code_cell(code, art.title))
            elif art.artifact_type == "chart" and isinstance(art.data, str):
                cells.append(_markdown_cell(
                    f"### {art.title}\n\n"
                    f"![{art.title}](data:image/png;base64,{art.data})"
                ))

    # Remaining artifacts not tied to a step
    for step_num, arts in artifact_by_step.items():
        if step_num < 0 or step_num >= len(payload.messages):
            for art in arts:
                if art.artifact_type == "code" and isinstance(art.data, str):
                    cells.append(_code_cell(art.data, art.title))
                elif art.artifact_type == "table" and isinstance(art.data, dict):
                    code = _table_to_pandas_code(art.data, art.title)
                    cells.append(_code_cell(code, art.title))

    notebook = {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {
                "name": "python",
                "version": "3.10.0",
            },
        },
        "cells": cells,
    }
    return notebook


def render_notebook_json(payload: ExportPayload) -> str:
    """Render notebook as a JSON string."""
    nb = render_notebook(payload)
    return json.dumps(nb, indent=2)


def export_notebook(payload: ExportPayload, output_path: str) -> str:
    """Export payload to a .ipynb file."""
    nb_json = render_notebook_json(payload)
    with open(output_path, "w") as f:
        f.write(nb_json)
    logger.info("Notebook exported to %s", output_path)
    return output_path


def _markdown_cell(source: str) -> dict[str, Any]:
    """Create a markdown cell."""
    return {
        "cell_type": "markdown",
        "metadata": {},
        "source": source.split("\n"),
    }


def _code_cell(source: str, title: str = "") -> dict[str, Any]:
    """Create a code cell."""
    lines = []
    if title:
        lines.append(f"# {title}")
    lines.extend(source.split("\n"))
    return {
        "cell_type": "code",
        "metadata": {},
        "source": lines,
        "execution_count": None,
        "outputs": [],
    }


def _table_to_pandas_code(data: dict, title: str = "") -> str:
    """Convert a table dict to pandas DataFrame construction code."""
    columns = data.get("columns", [])
    rows = data.get("rows", [])

    lines = ["import pandas as pd", ""]

    if rows and isinstance(rows[0], dict):
        lines.append(f"df = pd.DataFrame({json.dumps(rows[:50], default=str)})")
    elif rows and isinstance(rows[0], (list, tuple)):
        lines.append(f"data = {json.dumps(rows[:50], default=str)}")
        lines.append(f"df = pd.DataFrame(data, columns={json.dumps(columns)})")
    else:
        lines.append("df = pd.DataFrame()")

    lines.append("df")
    return "\n".join(lines)
