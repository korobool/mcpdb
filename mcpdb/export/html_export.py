def render_html(payload: ExportPayload) -> str:
    """Render a complete standalone HTML document from the export payload."""
    parts: list[str] = []
    parts.append("<!DOCTYPE html>")
    parts.append('<html lang="en"><head><meta charset="utf-8">')
    parts.append(f"<title>{html.escape(payload.title)}</title>")
    parts.append(f"<style>{_CSS}</style>")
    parts.append("</head><body>")

    # Title
    parts.append(f"<h1>{html.escape(payload.title)}</h1>")

    # Metadata
    meta_items = []
    if payload.metadata.get("source"):
        meta_items.append(f"Source: {html.escape(str(payload.metadata['source']))}")
    if payload.metadata.get("date"):
        meta_items.append(f"Date: {html.escape(str(payload.metadata['date']))}")
    if meta_items:
        parts.append(f'<div class="meta">{" | ".join(meta_items)}</div>')

    # Messages
    for msg in payload.messages:
        role_class = f"msg-{msg.role}"
        parts.append(f'<div class="msg {role_class}">')
        parts.append(f'<div class="role">{html.escape(msg.role)}</div>')
        parts.append(f'<div class="content">{html.escape(msg.content)}</div>')
        parts.append("</div>")

    # Artifacts
    for art in payload.artifacts:
        parts.append('<div class="artifact">')
        if art.title:
            parts.append(f"<h3>{html.escape(art.title)}</h3>")

        if art.artifact_type == "table" and isinstance(art.data, dict):
            parts.append(_render_table(art.data))
        elif art.artifact_type == "chart" and isinstance(art.data, str):
            parts.append(f'<div class="chart"><img src="data:image/png;base64,{art.data}" alt="{html.escape(art.title)}"></div>')
        elif art.artifact_type == "code" and isinstance(art.data, str):
            parts.append(f"<pre>{html.escape(art.data)}</pre>")
        parts.append("</div>")

    # Footer
    parts.append('<div class="footer">Generated by MCPDB</div>')
    parts.append("</body></html>")
    return "\n".join(parts)


def _render_table(data: dict) -> str:
    """Render a table dict (columns + rows) as HTML."""
    columns = data.get("columns", [])
    rows = data.get("rows", [])

    parts = ["<table><thead><tr>"]
    for col in columns:
        parts.append(f"<th>{html.escape(str(col))}</th>")
    parts.append("</tr></thead><tbody>")

    for row in rows:
        parts.append("<tr>")
        if isinstance(row, dict):
            for col in columns:
                parts.append(f"<td>{html.escape(str(row.get(col, '')))}</td>")
        elif isinstance(row, (list, tuple)):
            for val in row:
                parts.append(f"<td>{html.escape(str(val))}</td>")
        parts.append("</tr>")

    parts.append("</tbody></table>")
    return "".join(parts)
