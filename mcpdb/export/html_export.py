"""HTML export engine — renders conversation + artifacts to standalone HTML."""

from __future__ import annotations

import base64
import html
import logging
from dataclasses import dataclass, field
from typing import Any

logger = logging.getLogger("mcpdb.export.html")


@dataclass
class ExportMessage:
    """A message to include in the export."""

    role: str
    content: str
    timestamp: float = 0.0


@dataclass
class ExportArtifact:
    """An artifact to include in the export."""

    artifact_type: str  # "table", "chart", "code"
    title: str = ""
    data: Any = None  # DataFrame dict for tables, base64 PNG for charts, str for code
    step_number: int = 0


@dataclass
class ExportPayload:
    """Complete export payload."""

    title: str = "MCPDB Analysis"
    messages: list[ExportMessage] = field(default_factory=list)
    artifacts: list[ExportArtifact] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)


